--
-- install.sql -- one-shot installer for the AWR capacity-forecast suite.
-- =====================================================================
-- Creates every CAP_* / CAPV_ / CAPD_ / CAPF_ / CAPA_ object into the CURRENT
-- schema, wiring the portable seam to one of two data sources.
--
-- Usage (the caller MUST DEFINE deploy_mode first; see note below):
--
--   sqlplus / as sysdba
--   SQL> ALTER SESSION SET CONTAINER = PDB1;
--   SQL> ALTER SESSION SET CURRENT_SCHEMA = AWRCAP;   -- the owner create_owner.sql made
--   SQL> DEFINE deploy_mode = 'repository'            -- repository | fixture
--   SQL> @install.sql
--
-- The header prints the target schema. Installing into SYS still works but
-- prints a warning: a dedicated owner keeps the suite out of the dictionary
-- schema.
--
-- deploy_mode dispatch:
--   repository CAPV_* over the CAP_H_* copies of registered targets' AWR
--              (ddl/13, generated by repository/build.py, plus the collector
--              repository/cap_repo.sql). Needs CREATE DATABASE LINK granted
--              directly; no DBA_HIST_* grants. Register targets afterwards
--              with cap_repo.add_target and copy with cap_repo.collect.
--   fixture    CAPV_* over CAP_FIXTURE_* tables. Run test/fixture_install.sql
--              FIRST to create + populate them, then install with this mode.
--   local      retired in M25 (the suite read its own DBA_HIST_* views):
--              aborts before any DDL and names the upgrade path. A database
--              that measures itself is a repository and its own target
--              (install.sh ROLE=standalone, quickstart.sql).
--
-- Note on defaulting: SQL*Plus has no "define if unset", so &&deploy_mode below
-- will PROMPT once if you did not DEFINE it. Non-interactive callers (the test
-- harness, CI) always DEFINE it up front to avoid the prompt consuming a line.
--
-- Read-only against AWR data: the suite writes only to CAP_* tables it owns.
-- Operator tables (CAP_CONFIG, CAP_TBSPC_OVERRIDE) and derived tables
-- (CAP_ML_MODEL; the results layer's CAP_RUN, CAP_FIT_HIST, CAP_ALERT_STATE,
-- CAP_ALERT_EVENT) all survive a re-install: ddl/00_drop drops views only.
-- No AWR object is modified.
--
SET APPINFO OFF
SET APPINFO "AWRCAP/install.sql"
SET DEFINE '&'
SET VERIFY   OFF
SET FEEDBACK OFF
SET TIMING   OFF
SET TAB      OFF
SET SERVEROUTPUT ON SIZE UNLIMITED FORMAT WRAPPED
-- EXIT FAILURE, not SQL.SQLCODE: the OS keeps only the low 8 bits of the exit
-- status, so an ORA- code that is a multiple of 256 would exit 0.
WHENEVER SQLERROR EXIT FAILURE
WHENEVER OSERROR  EXIT FAILURE

-- Pin '.' as decimal separator so REGR_* / numeric literals are locale-safe.
ALTER SESSION SET NLS_NUMERIC_CHARACTERS = '.,';

PROMPT
PROMPT ============================================================
PROMPT  AWR Capacity Forecast -- install
PROMPT ============================================================

BEGIN
    IF LOWER(TRIM('&&deploy_mode')) = 'local' THEN
        RAISE_APPLICATION_ERROR(-20001, 'deploy_mode = local is retired (M25): every install'
            || ' is a repository, and a database that measures itself is its own target.'
            || ' Nothing was changed. To move a local install: run @uninstall.sql in its'
            || ' schema (it writes reports/cap_config_replay_<schema>_<ts>.sql and revokes'
            || ' the DBA_HIST grants), install standalone into a PDB (./install.sh --profile'
            || ' standalone, or @quickstart.sql), run the replay file in the new owner, then'
            || ' EXEC cap_repo.collect.');
    END IF;
END;
/

-- Resolve the seam script from deploy_mode. An unrecognised mode forces a
-- ZERO_DIVIDE so the install aborts loudly instead of silently skipping the
-- seam. LOWER() makes the mode case-insensitive.
COLUMN seam_script NEW_VALUE seam_script NOPRINT
SELECT 'ddl/' ||
       CASE LOWER(NVL('&&deploy_mode', 'repository'))
            WHEN 'repository' THEN '13_seam_repository.sql'
            WHEN 'fixture'    THEN '12_seam_fixture.sql'
            ELSE TO_CHAR(1/0)   -- invalid deploy_mode -> abort
       END AS seam_script
FROM   dual;

COLUMN cap_schema NEW_VALUE cap_schema NOPRINT
SELECT SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AS cap_schema FROM dual;

PROMPT  deploy_mode= &&deploy_mode
PROMPT  seam_script= &seam_script
PROMPT  schema     = &cap_schema
PROMPT

BEGIN
    IF SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') = 'SYS' THEN
        DBMS_OUTPUT.PUT_LINE('  ############################################################');
        DBMS_OUTPUT.PUT_LINE('  WARNING: installing into SYS.');
        DBMS_OUTPUT.PUT_LINE('  Every CAP* object will be owned by SYS in this container.');
        DBMS_OUTPUT.PUT_LINE('  This works, but it mixes the suite into the dictionary');
        DBMS_OUTPUT.PUT_LINE('  schema. For a real install, create a dedicated owner with');
        DBMS_OUTPUT.PUT_LINE('  @create_owner.sql and install as that user.');
        DBMS_OUTPUT.PUT_LINE('  ############################################################');
    END IF;
END;
/

