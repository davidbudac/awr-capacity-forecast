-- --------------------------------------------------------------------
-- Recompile, then check. A re-install drops and recreates the views, which
-- leaves any dependent object INVALID (e.g. CAP_REPORT_SPOOL from
-- install_jobs.sql, which reads CAPR_ALERTS), and nothing else recompiles it.
-- Both steps read ALL_OBJECTS on owner = CURRENT_SCHEMA: USER_OBJECTS follows
-- the session user, so it looks in the wrong schema under
-- ALTER SESSION SET CURRENT_SCHEMA.
-- --------------------------------------------------------------------
SET DEFINE '&'
SET SERVEROUTPUT ON SIZE UNLIMITED FORMAT WRAPPED
DECLARE
    v_owner VARCHAR2(128) := SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA');
    v_sql   VARCHAR2(400);
BEGIN
    -- Two passes: an object that failed because its own dependency was still
    -- invalid compiles on the second.
    FOR pass IN 1 .. 2 LOOP
        FOR r IN (
            SELECT object_name, object_type
            FROM   all_objects
            WHERE  owner  = v_owner
              AND  status = 'INVALID'
              AND  REGEXP_LIKE(object_name, '^CAP[VDFAR]?_')
              AND  object_type IN ('VIEW', 'PROCEDURE', 'FUNCTION', 'PACKAGE',
                                   'PACKAGE BODY', 'TYPE', 'TYPE BODY',
                                   'TRIGGER', 'SYNONYM')
            ORDER BY DECODE(object_type, 'TYPE', 1, 'PACKAGE', 2, 'VIEW', 3,
                                         'SYNONYM', 3, 'FUNCTION', 4,
                                         'PROCEDURE', 4, 'TYPE BODY', 5,
                                         'PACKAGE BODY', 5, 6),
                     object_name
        ) LOOP
            v_sql := 'ALTER '
                  || CASE r.object_type
                         WHEN 'PACKAGE BODY' THEN 'PACKAGE'
                         WHEN 'TYPE BODY'    THEN 'TYPE'
                         ELSE r.object_type
                     END
                  || ' ' || DBMS_ASSERT.ENQUOTE_NAME(v_owner, FALSE)
                  || '.' || DBMS_ASSERT.ENQUOTE_NAME(r.object_name, FALSE)
                  || CASE WHEN r.object_type IN ('PACKAGE BODY', 'TYPE BODY')
                          THEN ' COMPILE BODY' ELSE ' COMPILE' END;
            BEGIN
                EXECUTE IMMEDIATE v_sql;
                DBMS_OUTPUT.PUT_LINE('  recompiled ' || r.object_type || ' ' || r.object_name);
            EXCEPTION
                WHEN OTHERS THEN
                    -- ORA-24344 (compiled with errors) lands here; the check
                    -- below lists whatever is still invalid.
                    IF pass = 2 THEN
                        DBMS_OUTPUT.PUT_LINE('  recompile failed: ' || r.object_type || ' '
                                             || r.object_name || ' (' || SQLERRM || ')');
                    END IF;
            END;
        END LOOP;
    END LOOP;
END;
/

-- Any INVALID object among our prefixes is a real install failure, in every
-- deploy mode.
DECLARE
    v_bad   PLS_INTEGER  := 0;
BEGIN
    FOR r IN (
        SELECT object_name, object_type
        FROM   all_objects
        WHERE  owner  = SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA')
          AND  status = 'INVALID'
          AND  REGEXP_LIKE(object_name, '^CAP[VDFAR]?_')
        ORDER BY object_name
    ) LOOP
        v_bad := v_bad + 1;
        DBMS_OUTPUT.PUT_LINE('  INVALID ' || r.object_type || ' ' || r.object_name);
    END LOOP;

    IF v_bad > 0 THEN
        RAISE_APPLICATION_ERROR(-20001,
            'Install incomplete: ' || v_bad || ' object(s) invalid in schema '
            || SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') || ' (see list above). '
            || 'Check CREATE DATABASE LINK (repository mode) or the CAP_FIXTURE_* '
            || 'tables (fixture mode).');
    END IF;
    DBMS_OUTPUT.PUT_LINE('  All CAP* objects valid in schema '
                         || SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') || '.');
END;
/

PROMPT
SET DEFINE '&'
-- A fresh repository has no target yet, so its first step is registering one,
-- unless target/self.sql ran in this session (the standalone path), whose
-- repository/self.sql registers this database next.
-- TERMOUT OFF because a NOPRINT-only SELECT still prints blank lines.
SET TERMOUT OFF
COLUMN cap_self_in NEW_VALUE cap_self_name NOPRINT
SELECT NULL AS cap_self_in FROM dual WHERE 1 = 0;
COLUMN cap_self_in CLEAR
COLUMN cap_next1 NEW_VALUE cap_next1 NOPRINT
COLUMN cap_next2 NEW_VALUE cap_next2 NOPRINT
COLUMN cap_next3 NEW_VALUE cap_next3 NOPRINT
SELECT CASE WHEN m = 'repository' AND s IS NOT NULL
            THEN 'repository/self.sql  (registers this database as target ' || s || ')'
            WHEN m = 'repository'
            THEN 'EXEC cap_repo.add_target(''<NAME>'', ''//<host>:<port>/<service>'', ''C##AWRRDR'', ''<password>'')'
            ELSE 'report/report.sql  (text capacity report)' END AS cap_next1,
       CASE WHEN m = 'repository' AND s IS NOT NULL
            THEN 'EXEC cap_repo.collect  (repository/self.sql runs it too)'
            WHEN m = 'repository'
            THEN 'EXEC cap_repo.collect  (copies AWR from every enabled target)'
            ELSE 'cap_forecast_ml.train_all  (optional Tier 2 ESM models)' END AS cap_next2,
       CASE WHEN m = 'repository'
            THEN 'then report/report.sql, cap_forecast_ml.train_all, cap_results.refresh as usual'
            ELSE 'cap_results.refresh  (optional run history + alert state)' END AS cap_next3
FROM   (SELECT LOWER('&&deploy_mode') AS m, '&cap_self_name' AS s FROM dual);
COLUMN cap_next1 CLEAR
COLUMN cap_next2 CLEAR
COLUMN cap_next3 CLEAR
SET TERMOUT ON
PROMPT ============================================================
PROMPT  Install complete (deploy_mode = &&deploy_mode, schema = &cap_schema).
PROMPT  Next: &cap_next1
PROMPT        &cap_next2
PROMPT        &cap_next3
PROMPT ============================================================
PROMPT

WHENEVER SQLERROR CONTINUE
WHENEVER OSERROR  CONTINUE
