#!/usr/bin/env python3
"""Generate the static halves of the HTML report.

report/report_html.sql spools the page as

    page_head.sql   doctype, <head>, report.css, the empty #app mount
    (its own block) the data, one <script type="application/json">
    page_tail.sql   report.js, </body></html>

This script writes page_head.sql and page_tail.sql from report.css and
report.js. Edit those two sources and rerun it; never edit the .sql output.

    python3 report/html/build.py            regenerate the two .sql files
    python3 report/html/build.py --check    exit 1 if they are out of date
    python3 report/html/build.py --preview DATA OUT
        DATA is a spooled report (.html) or a bare JSON file; writes OUT as
        the page SQL*Plus would spool, with the current CSS and JS.
"""
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
CSS = HERE / "report.css"
JS = HERE / "report.js"
HEAD_SQL = HERE / "page_head.sql"
TAIL_SQL = HERE / "page_tail.sql"

CHUNK = 1000          # SQL*Plus reads at most 2499 bytes per script line
LINES_PER_BLOCK = 400  # keep each anonymous block small for the PL/SQL compiler
DATA_RE = re.compile(
    r'<script type="application/json" id="cap-data">\s*(.*?)\s*</script>', re.S)


def ascii_css(text):
    bad = sorted({c for c in text if ord(c) >= 128})
    if bad:
        raise SystemExit(f"report.css: use CSS escapes, not {bad!r}")
    return text


def head_html():
    return "\n".join([
        "<!doctype html>",
        '<html lang="en">',
        "<head>",
        '<meta charset="utf-8">',
        '<meta name="viewport" content="width=device-width, initial-scale=1">',
        '<meta name="color-scheme" content="light dark">',
        "<title>AWR capacity report</title>",
        "<style>",
        ascii_css(CSS.read_text().rstrip("\n")),
        "</style>",
        "</head>",
        "<body>",
        '<div id="app"><noscript><p class="noscript">This report draws its '
        "charts with JavaScript. Open it in a browser with scripts enabled."
        "</p></noscript></div>",
    ])


def ascii_js(text):
    """\\uXXXX for every non-ASCII character: DBMS_OUTPUT and the client
    character set would turn it into '?' in the spool. The renderer keeps
    non-ASCII text inside string literals only, where the escape is exact."""
    return "".join(c if ord(c) < 128 else "\\u%04x" % ord(c) for c in text)


def tail_html():
    return "\n".join([
        "<script>",
        ascii_js(JS.read_text().rstrip("\n")),
        "</script>",
        "</body>",
        "</html>",
    ])


def to_sql(html, source):
    if "~'" in html:
        raise SystemExit(f"{source}: contains ~' which would end a q'~...~' literal")
    out = [
        f"-- GENERATED by report/html/build.py from {source}. Do not edit:",
        "-- change the source and rerun python3 report/html/build.py.",
        "SET DEFINE OFF",
    ]
    lines = html.split("\n")
    for b in range(0, len(lines), LINES_PER_BLOCK):
        out.append("BEGIN")
        for line in lines[b:b + LINES_PER_BLOCK]:
            parts = [line[i:i + CHUNK] for i in range(0, len(line), CHUNK)] or [""]
            for part in parts[:-1]:
                out.append(f"  DBMS_OUTPUT.PUT(q'~{part}~');")
            last = parts[-1]
            if last.strip() == "":
                out.append("  DBMS_OUTPUT.PUT_LINE(NULL);")
            else:
                out.append(f"  DBMS_OUTPUT.PUT_LINE(q'~{last}~');")
        out.append("END;")
        out.append("/")
    return "\n".join(out) + "\n"


def generated():
    return {
        HEAD_SQL: to_sql(head_html(), "report/html/report.css"),
        TAIL_SQL: to_sql(tail_html(), "report/html/report.js"),
    }


def preview(data_path, out_path):
    raw = pathlib.Path(data_path).read_text()
    m = DATA_RE.search(raw)
    data = m.group(1) if m else raw
    json.loads(data)
    page = "\n".join([
        head_html(),
        '<script type="application/json" id="cap-data">',
        data,
        "</script>",
        tail_html(),
    ])
    pathlib.Path(out_path).write_text(page + "\n")


def main(argv):
    if len(argv) >= 1 and argv[0] == "--preview":
        if len(argv) != 3:
            raise SystemExit(__doc__)
        preview(argv[1], argv[2])
        return 0
    stale = [p for p, text in generated().items()
             if not p.exists() or p.read_text() != text]
    if argv[:1] == ["--check"]:
        for p in stale:
            print(f"out of date: {p.relative_to(HERE.parent.parent)} "
                  "(run python3 report/html/build.py)")
        return 1 if stale else 0
    for p, text in generated().items():
        p.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
