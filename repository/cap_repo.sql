CREATE OR REPLACE PACKAGE cap_repo AUTHID DEFINER AS
    -- Register a target and find its DBIDs. Two ways to reach it:
    --   p_connect + p_user + p_password  create the DB link CAP_<name> here
    --                                    (dropped again by remove_target);
    --   p_db_link                        use a link of this schema the DBA
    --                                    made (wallet, proxy), kept on remove.
    -- Where this database runs with GLOBAL_NAMES = TRUE a link must be named
    -- after the target's global name (ORA-02085 otherwise), so the link
    -- becomes <p_global_name>@CAP_<name>; without p_global_name that case
    -- fails with ORA-20074. target/prepare.sql prints the global name.
    -- Every copied view is probed over the link first; a view the reader
    -- cannot see fails the call (ORA-20072) and leaves nothing behind.
    -- Copies nothing yet: run collect.
    PROCEDURE add_target(p_name        IN VARCHAR2,
                         p_connect     IN VARCHAR2 DEFAULT NULL,
                         p_user        IN VARCHAR2 DEFAULT NULL,
                         p_password    IN VARCHAR2 DEFAULT NULL,
                         p_db_link     IN VARCHAR2 DEFAULT NULL,
                         p_global_name IN VARCHAR2 DEFAULT NULL);

    -- Copy every snapshot not copied yet, for one target or (NULL) every
    -- enabled one. The first collect of a DBID backfills what the target
    -- still holds. A failing target is logged and the rest go on; afterwards
    -- ORA-20070 names how many failed (details in CAP_COLLECT_LOG).
    PROCEDURE collect(p_name        IN VARCHAR2    DEFAULT NULL,
                      p_chunk_snaps IN PLS_INTEGER DEFAULT 500);

    -- Pause (N) or resume (Y) collection; the copies stay.
    PROCEDURE set_enabled(p_name IN VARCHAR2, p_enabled IN VARCHAR2);

    -- Forget a target: delete its copies and registry rows, drop the link if
    -- add_target created it. CAP_COLLECT_LOG keeps its history.
    PROCEDURE remove_target(p_name IN VARCHAR2);

    -- The reader's password changed on the target (rotation, expiry):
    -- recreate the link add_target made; the copies stay.
    PROCEDURE set_link_password(p_name IN VARCHAR2, p_password IN VARCHAR2);

    -- Delete the fact copies of snapshots that ended more than p_days
    -- (default the repo_retention_days knob; 0 = keep everything) days ago,
    -- per DBID, and older CAP_COLLECT_LOG rows, in one transaction. The
    -- dimension copies stay. A knob that CAP_CFG_CHECK reports BAD is
    -- refused; p_days overrides it.
    PROCEDURE purge(p_days IN NUMBER DEFAULT NULL);

    -- NULL when the target's link answers and its reader can read every
    -- copied view, else the error text. Never raises; rolls back the
    -- caller's transaction (the remote SELECT opens a distributed one).
    FUNCTION ping(p_name IN VARCHAR2) RETURN VARCHAR2;

    -- When the reader's password expires on the target (USER_USERS over the
    -- link; doctor.sql check 11 warns ahead of it). NULL when it never
    -- expires or the link cannot answer (ping says why). Never raises; rolls
    -- back the caller's transaction as ping does.
    FUNCTION reader_expiry(p_name IN VARCHAR2) RETURN DATE;

    -- Every procedure above labels its session MODULE 'AWRCAP/cap_repo.<name>'
    -- (collect: ACTION = the target and DBID it copies) and puts the caller's
    -- MODULE / ACTION back when it returns or raises. The target's session
    -- behind the link does not inherit them, so it is labelled too: MODULE
    -- as here, ACTION 'from <owner>@<container>' of this repository.
END cap_repo;
/

CREATE OR REPLACE PACKAGE BODY cap_repo AS

    e_locked EXCEPTION;
    PRAGMA EXCEPTION_INIT(e_locked, -54);
    e_global_names EXCEPTION;
    PRAGMA EXCEPTION_INIT(e_global_names, -2085);

    PROCEDURE say(p_txt IN VARCHAR2) IS
    BEGIN
        DBMS_OUTPUT.PUT_LINE('  ' || p_txt);
    END say;

    PROCEDURE log_event(p_target IN VARCHAR2, p_dbid IN NUMBER, p_status IN VARCHAR2,
                        p_from IN NUMBER DEFAULT NULL, p_to IN NUMBER DEFAULT NULL,
                        p_rows IN NUMBER DEFAULT NULL, p_secs IN NUMBER DEFAULT NULL,
                        p_msg IN VARCHAR2 DEFAULT NULL) IS
        PRAGMA AUTONOMOUS_TRANSACTION;
    BEGIN
        INSERT INTO cap_collect_log (target_name, dbid, status, snap_from, snap_to,
                                     n_rows, elapsed_s, message)
        VALUES (p_target, p_dbid, p_status, p_from, p_to, p_rows, p_secs,
                SUBSTR(p_msg, 1, 4000));
        COMMIT;
    END log_event;

    FUNCTION norm_name(p_name IN VARCHAR2) RETURN VARCHAR2 IS
        v VARCHAR2(200) := UPPER(TRIM(p_name));
    BEGIN
        IF v IS NULL OR NOT REGEXP_LIKE(v, '^[A-Z][A-Z0-9_]{0,25}$') THEN
            RAISE_APPLICATION_ERROR(-20071, 'target name must be a letter then up to 25'
                                            || ' letters, digits or _, not "' || p_name || '"');
        END IF;
        RETURN v;
    END norm_name;

    FUNCTION get_target(p_name IN VARCHAR2) RETURN cap_target%ROWTYPE IS
        t      cap_target%ROWTYPE;
        v_name cap_target.target_name%TYPE := norm_name(p_name);
    BEGIN
        SELECT * INTO t FROM cap_target WHERE target_name = v_name;
        RETURN t;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20071, 'no target ' || UPPER(p_name)
                                            || ' (see CAP_TARGET)');
    END get_target;

    -- Over the target's PUBLIC EXECUTE on DBMS_APPLICATION_INFO; a target
    -- that revoked it just shows an unlabelled session.
    PROCEDURE label_remote(p_link IN VARCHAR2) IS
        l_mod VARCHAR2(64);
        l_act VARCHAR2(64);
    BEGIN
        DBMS_APPLICATION_INFO.READ_MODULE(l_mod, l_act);
        EXECUTE IMMEDIATE 'BEGIN dbms_application_info.set_module@' || p_link || '(:m, :a); END;'
            USING l_mod, SUBSTR('from ' || SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') || '@'
                                || SYS_CONTEXT('USERENV', 'CON_NAME'), 1, 32);
    EXCEPTION
        WHEN OTHERS THEN NULL;
    END label_remote;

    PROCEDURE close_link(p_link IN VARCHAR2) IS
    BEGIN
        DBMS_SESSION.CLOSE_DATABASE_LINK(p_link);
    EXCEPTION
        WHEN OTHERS THEN NULL;   -- not open, or a transaction still uses it
    END close_link;

    PROCEDURE create_link(p_link IN VARCHAR2, p_user IN VARCHAR2, p_password IN VARCHAR2,
                          p_connect IN VARCHAR2) IS
    BEGIN
        EXECUTE IMMEDIATE 'CREATE DATABASE LINK ' || p_link || ' CONNECT TO ' || p_user
                          || ' IDENTIFIED BY "' || p_password || '" USING '''
                          || p_connect || '''';
    END create_link;

    PROCEDURE drop_link(p_link IN VARCHAR2) IS
    BEGIN
        close_link(p_link);
        EXECUTE IMMEDIATE 'DROP DATABASE LINK ' || p_link;
    EXCEPTION
        WHEN OTHERS THEN NULL;
    END drop_link;

    -- CAP_<name>, or <global name>@CAP_<name> (a connection qualifier) where
    -- GLOBAL_NAMES = TRUE refuses a link not named after the target's global
    -- name. Returns the link it made; a failure leaves no link behind.
    FUNCTION owned_link(p_name IN VARCHAR2, p_connect IN VARCHAR2, p_user IN VARCHAR2,
                        p_password IN VARCHAR2, p_global_name IN VARCHAR2) RETURN VARCHAR2 IS
        v_link VARCHAR2(128) := 'CAP_' || p_name;
        v_n    NUMBER;
        v_err  VARCHAR2(4000);
    BEGIN
        create_link(v_link, p_user, p_password, p_connect);
        BEGIN
            EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM dual@' || v_link INTO v_n;
            RETURN v_link;
        EXCEPTION
            WHEN e_global_names THEN
                v_err := SQLERRM;
            WHEN OTHERS THEN
                ROLLBACK;
                drop_link(v_link);
                RAISE;
        END;
        ROLLBACK;
        drop_link(v_link);
        IF p_global_name IS NULL THEN
            RAISE_APPLICATION_ERROR(-20074, 'GLOBAL_NAMES is TRUE here, so the link must be'
                || ' named after the target''s global name: pass p_global_name (target/prepare.sql'
                || ' prints it). ' || v_err);
        END IF;
        v_link := UPPER(p_global_name) || '@' || v_link;
        create_link(v_link, p_user, p_password, p_connect);
        RETURN v_link;
    END owned_link;

    -- Fail unless the link answers and the reader can see every copied view.
    PROCEDURE probe(p_link IN VARCHAR2) IS
        v_n       NUMBER;
        v_missing VARCHAR2(4000);
    BEGIN
        EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM dual@' || p_link INTO v_n;
        label_remote(p_link);
        FOR s IN (SELECT source_name FROM cap_repo_source ORDER BY seq) LOOP
            BEGIN
                EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM dba_hist_' || LOWER(s.source_name)
                                  || '@' || p_link || ' WHERE 1 = 0' INTO v_n;
            EXCEPTION
                WHEN OTHERS THEN
                    v_missing := SUBSTR(v_missing || CASE WHEN v_missing IS NOT NULL THEN ', ' END
                                        || 'DBA_HIST_' || s.source_name, 1, 3000);
            END;
        END LOOP;
        ROLLBACK;
        IF v_missing IS NOT NULL THEN
            RAISE_APPLICATION_ERROR(-20072, 'the reader behind link ' || p_link
                || ' cannot read ' || v_missing || '. Run target/prepare.sql on the target.');
        END IF;
    END probe;

    -- Add the target's new DBIDs; a DBID another target owns is refused.
    PROCEDURE discover(p_id IN NUMBER, p_name IN VARCHAR2, p_link IN VARCHAR2) IS
        TYPE t_ids IS TABLE OF NUMBER;
        v_ids   t_ids;
        v_owner NUMBER;
        v_other cap_target.target_name%TYPE;
    BEGIN
        EXECUTE IMMEDIATE 'SELECT DISTINCT dbid FROM dba_hist_snapshot@' || p_link
            BULK COLLECT INTO v_ids;
        FOR i IN 1 .. v_ids.COUNT LOOP
            BEGIN
                SELECT target_id INTO v_owner FROM cap_target_dbid WHERE dbid = v_ids(i);
                IF v_owner <> p_id THEN
                    SELECT target_name INTO v_other FROM cap_target WHERE target_id = v_owner;
                    log_event(p_name, v_ids(i), 'COLLISION',
                              p_msg => 'DBID ' || v_ids(i) || ' already belongs to target '
                                       || v_other || ' (a clone without NID?): not copied');
                    say('[WARN] DBID ' || v_ids(i) || ' already belongs to ' || v_other
                        || ': not copied for ' || p_name);
                END IF;
            EXCEPTION
                WHEN NO_DATA_FOUND THEN
                    INSERT INTO cap_target_dbid (dbid, target_id) VALUES (v_ids(i), p_id);
                    say('DBID ' || v_ids(i) || ' registered for ' || p_name);
            END;
        END LOOP;
    END discover;

    -- Copy one DBID up to the target's newest snapshot. FALSE = it failed.
    FUNCTION collect_dbid(t IN cap_target%ROWTYPE, p_dbid IN NUMBER,
                          p_chunk IN PLS_INTEGER) RETURN BOOLEAN IS
        v_min    NUMBER;
        v_max    NUMBER;
        v_prev   NUMBER;
        v_n_max  NUMBER;
        v_n_prev NUMBER;
        v_held   VARCHAR2(200);
        v_hwm    NUMBER;
        v_end    NUMBER;
        v_first  NUMBER;
        v_rows   NUMBER := 0;
        v_t0     PLS_INTEGER := DBMS_UTILITY.GET_TIME;
        v_sql    VARCHAR2(4000);

        FUNCTION secs RETURN NUMBER IS
        BEGIN
            RETURN ROUND((DBMS_UTILITY.GET_TIME - v_t0) / 100, 1);
        END secs;
    BEGIN
        DBMS_APPLICATION_INFO.SET_ACTION(SUBSTR(t.target_name || ' ' || p_dbid, 1, 32));
        EXECUTE IMMEDIATE 'SELECT MIN(snap_id), MAX(snap_id), MAX(CASE WHEN rn = 2 THEN snap_id END),'
                          || ' MAX(CASE WHEN rn = 1 THEN n_inst END), MAX(CASE WHEN rn = 2 THEN n_inst END)'
                          || ' FROM (SELECT snap_id, COUNT(DISTINCT instance_number) AS n_inst,'
                          || ' ROW_NUMBER() OVER (ORDER BY snap_id DESC) AS rn'
                          || ' FROM dba_hist_snapshot@' || t.db_link || ' WHERE dbid = :1 GROUP BY snap_id)'
            INTO v_min, v_max, v_prev, v_n_max, v_n_prev USING p_dbid;
        IF v_max IS NULL THEN
            ROLLBACK;
            log_event(t.target_name, p_dbid, 'NOTHING', p_secs => secs,
                      p_msg => 'no snapshots for this DBID on the target any more');
            RETURN TRUE;
        END IF;
        -- RAC: one instance can finish snap_id N before another. Facts are
        -- copied once, above the high-water mark, so a half-copied N would
        -- never be completed; N waits for the next collect instead.
        IF v_n_max < v_n_prev THEN
            v_held := 'snap_id ' || v_max || ' held back: ' || v_n_max || ' of ' || v_n_prev
                      || ' instances have completed it';
            v_max  := v_prev;
        END IF;

        LOOP
            BEGIN
                SELECT last_snap_id INTO v_hwm
                FROM   cap_target_dbid
                WHERE  dbid = p_dbid AND target_id = t.target_id
                FOR UPDATE NOWAIT;
            EXCEPTION
                WHEN e_locked THEN
                    ROLLBACK;
                    log_event(t.target_name, p_dbid, 'SKIPPED', p_secs => secs,
                              p_msg => 'another collect holds this DBID');
                    say(t.target_name || ' DBID ' || p_dbid || ': another collect is running, skipped');
                    RETURN TRUE;
                WHEN NO_DATA_FOUND THEN
                    ROLLBACK;
                    say(t.target_name || ' DBID ' || p_dbid || ': removed meanwhile, stopped');
                    RETURN TRUE;
            END;

            IF v_hwm > 0 AND v_hwm < v_min - 1 AND v_first IS NULL THEN
                log_event(t.target_name, p_dbid, 'GAP', v_hwm + 1, v_min - 1,
                          p_msg => 'snapshots ' || (v_hwm + 1) || '..' || (v_min - 1)
                                   || ' aged out of the target before they were copied');
                say('[WARN] ' || t.target_name || ' DBID ' || p_dbid || ': snapshots '
                    || (v_hwm + 1) || '..' || (v_min - 1) || ' were purged on the target'
                    || ' before collection (AWR retention shorter than the outage)');
            END IF;

            IF v_hwm > v_max AND v_first IS NULL THEN
                log_event(t.target_name, p_dbid, 'BEHIND', v_max, v_hwm,
                          p_msg => 'newest snap_id ' || v_max || ' on the target is below the'
                                   || ' high-water mark ' || v_hwm || ': was AWR recreated there?');
                say('[WARN] ' || t.target_name || ' DBID ' || p_dbid || ': the target''s newest'
                    || ' snap_id ' || v_max || ' is below the high-water mark ' || v_hwm);
            END IF;
            IF v_hwm >= v_max THEN
                COMMIT;
                EXIT;
            END IF;
            -- The window starts at the high-water mark, not at the oldest
            -- snapshot: AWR purges its tables unevenly, and fact rows of a
            -- snapshot already gone from DBA_HIST_SNAPSHOT are still copied,
            -- because the target's own views still show them.
            v_end   := LEAST(v_max, GREATEST(v_hwm, v_min - 1) + p_chunk);
            v_first := NVL(v_first, v_hwm + 1);

            FOR s IN (SELECT kind, pull_sql FROM cap_repo_source ORDER BY seq) LOOP
                v_sql := REPLACE(s.pull_sql, '{LINK}', t.db_link);
                CASE s.kind
                    WHEN 'F' THEN EXECUTE IMMEDIATE v_sql USING p_dbid, v_hwm, v_end;
                    WHEN 'D' THEN EXECUTE IMMEDIATE v_sql USING p_dbid;
                    WHEN 'S' THEN EXECUTE IMMEDIATE v_sql USING p_dbid, p_dbid, v_hwm, v_end;
                END CASE;
                v_rows := v_rows + SQL%ROWCOUNT;
            END LOOP;

            UPDATE cap_target_dbid
            SET    last_snap_id = v_end, last_collect = SYSDATE
            WHERE  dbid = p_dbid;
            COMMIT;
        END LOOP;

        UPDATE cap_target_dbid SET last_collect = SYSDATE WHERE dbid = p_dbid;
        COMMIT;
        log_event(t.target_name, p_dbid, CASE WHEN v_first IS NULL THEN 'NOTHING' ELSE 'OK' END,
                  v_first, CASE WHEN v_first IS NOT NULL THEN v_max END, v_rows, secs, v_held);
        say(t.target_name || ' DBID ' || p_dbid || ': '
            || CASE WHEN v_first IS NULL THEN 'up to date at snap_id ' || v_max
                    ELSE 'snap_id ' || v_first || '..' || v_max || ', ' || v_rows || ' rows' END
            || ' (' || secs || ' s)' || CASE WHEN v_held IS NOT NULL THEN '; ' || v_held END);
        RETURN TRUE;
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            log_event(t.target_name, p_dbid, 'ERROR', v_first, v_end, v_rows, secs,
                      SQLERRM || CHR(10) || DBMS_UTILITY.FORMAT_ERROR_BACKTRACE);
            say('[FAIL] ' || t.target_name || ' DBID ' || p_dbid || ': ' || SQLERRM);
            RETURN FALSE;
    END collect_dbid;

    PROCEDURE add_target(p_name        IN VARCHAR2,
                         p_connect     IN VARCHAR2 DEFAULT NULL,
                         p_user        IN VARCHAR2 DEFAULT NULL,
                         p_password    IN VARCHAR2 DEFAULT NULL,
                         p_db_link     IN VARCHAR2 DEFAULT NULL,
                         p_global_name IN VARCHAR2 DEFAULT NULL) IS
        v_name  cap_target.target_name%TYPE := norm_name(p_name);
        v_link  VARCHAR2(128);
        v_owned VARCHAR2(1);
        v_id    NUMBER;
        v_n     NUMBER;
        v_cons  VARCHAR2(4000);
        l_mod   VARCHAR2(64);
        l_act   VARCHAR2(64);
    BEGIN
        DBMS_APPLICATION_INFO.READ_MODULE(l_mod, l_act);
        DBMS_APPLICATION_INFO.SET_MODULE('AWRCAP/cap_repo.add_target', NULL);
        SELECT COUNT(*) INTO v_n FROM cap_target WHERE target_name = v_name;
        IF v_n > 0 THEN
            RAISE_APPLICATION_ERROR(-20073, 'target ' || v_name || ' is already registered');
        END IF;

        IF p_db_link IS NOT NULL THEN
            v_link  := UPPER(DBMS_ASSERT.QUALIFIED_SQL_NAME(p_db_link));
            v_owned := 'N';
        ELSE
            IF p_connect IS NULL OR p_user IS NULL OR p_password IS NULL THEN
                RAISE_APPLICATION_ERROR(-20071, 'give p_connect, p_user and p_password,'
                                                || ' or p_db_link for an existing link');
            END IF;
            IF NOT REGEXP_LIKE(p_user, '^[A-Za-z][A-Za-z0-9_$#]{0,127}$')
               OR INSTR(p_password, '"') > 0 OR INSTR(p_connect, '''') > 0 THEN
                RAISE_APPLICATION_ERROR(-20071, 'p_user must be a plain name, p_password'
                                                || ' without ", p_connect without a quote');
            END IF;
            IF p_global_name IS NOT NULL AND NOT REGEXP_LIKE(p_global_name,
                   '^[A-Za-z][A-Za-z0-9_$#]*(\.[A-Za-z][A-Za-z0-9_$#]*)*$')
               OR LENGTH(p_global_name) + LENGTH('@CAP_' || v_name) > 128 THEN
                RAISE_APPLICATION_ERROR(-20071, 'p_global_name must be the target''s global'
                    || ' name as target/prepare.sql prints it (DB_NAME.DOMAIN), not ' || p_global_name);
            END IF;
            v_owned := 'Y';
        END IF;

        BEGIN
            IF v_owned = 'Y' THEN
                v_link := owned_link(v_name, p_connect, p_user, p_password, p_global_name);
            END IF;
            probe(v_link);
            INSERT INTO cap_target (target_name, db_link, link_owned, connect_string, link_user)
            VALUES (v_name, v_link, v_owned, p_connect, UPPER(p_user))
            RETURNING target_id INTO v_id;
            discover(v_id, v_name, v_link);
            EXECUTE IMMEDIATE
                'SELECT COUNT(DISTINCT con_dbid), LISTAGG(DISTINCT pdb_name, '', '' ON OVERFLOW'
                || ' TRUNCATE) WITHIN GROUP (ORDER BY pdb_name) FROM dba_hist_pdb_instance@' || v_link
                INTO v_n, v_cons;
            COMMIT;
        EXCEPTION
            WHEN OTHERS THEN
                ROLLBACK;
                IF v_owned = 'Y' AND v_link IS NOT NULL THEN
                    drop_link(v_link);
                END IF;
                RAISE;
        END;
        close_link(v_link);
        say('target ' || v_name || ' registered over link ' || v_link
            || CASE WHEN v_n > 0 THEN '; containers visible: ' || v_cons END);
        say('next: EXEC cap_repo.collect(''' || v_name || ''')');
        DBMS_APPLICATION_INFO.SET_MODULE(l_mod, l_act);
    EXCEPTION
        WHEN OTHERS THEN
            DBMS_APPLICATION_INFO.SET_MODULE(l_mod, l_act);
            RAISE;
    END add_target;

    PROCEDURE collect(p_name        IN VARCHAR2    DEFAULT NULL,
                      p_chunk_snaps IN PLS_INTEGER DEFAULT 500) IS
        v_name   cap_target.target_name%TYPE;
        v_fail   PLS_INTEGER := 0;
        v_seen   PLS_INTEGER := 0;
        v_t      cap_target%ROWTYPE;
        t        cap_target%ROWTYPE;
        l_mod   VARCHAR2(64);
        l_act   VARCHAR2(64);
    BEGIN
        DBMS_APPLICATION_INFO.READ_MODULE(l_mod, l_act);
        DBMS_APPLICATION_INFO.SET_MODULE('AWRCAP/cap_repo.collect', NULL);
        IF p_chunk_snaps IS NULL OR p_chunk_snaps < 1 THEN
            RAISE_APPLICATION_ERROR(-20071, 'p_chunk_snaps must be at least 1');
        END IF;
        IF p_name IS NOT NULL THEN
            v_t := get_target(p_name);
            IF v_t.enabled = 'N' THEN
                RAISE_APPLICATION_ERROR(-20071, 'target ' || v_t.target_name
                                                || ' is disabled (cap_repo.set_enabled)');
            END IF;
            v_name := v_t.target_name;
        END IF;

        FOR r IN (SELECT target_id FROM cap_target
                  WHERE  enabled = 'Y' AND (v_name IS NULL OR target_name = v_name)
                  ORDER  BY target_name) LOOP
            SELECT * INTO t FROM cap_target WHERE target_id = r.target_id;
            v_seen := v_seen + 1;
            BEGIN
                DBMS_APPLICATION_INFO.SET_ACTION(SUBSTR(t.target_name, 1, 32));
                discover(t.target_id, t.target_name, t.db_link);
                label_remote(t.db_link);
                COMMIT;
            EXCEPTION
                WHEN OTHERS THEN
                    ROLLBACK;
                    v_fail := v_fail + 1;
                    log_event(t.target_name, NULL, 'ERROR',
                              p_msg => 'link ' || t.db_link || ': ' || SQLERRM);
                    say('[FAIL] ' || t.target_name || ': ' || SQLERRM);
                    close_link(t.db_link);
                    CONTINUE;
            END;
            FOR d IN (SELECT dbid FROM cap_target_dbid
                      WHERE  target_id = t.target_id ORDER BY dbid) LOOP
                IF NOT collect_dbid(t, d.dbid, p_chunk_snaps) THEN
                    v_fail := v_fail + 1;
                END IF;
            END LOOP;
            close_link(t.db_link);
        END LOOP;

        IF v_seen = 0 THEN
            say('no enabled target (cap_repo.add_target registers one)');
        END IF;
        IF v_fail > 0 THEN
            RAISE_APPLICATION_ERROR(-20070, v_fail || ' collect(s) failed; see CAP_COLLECT_LOG');
        END IF;
        DBMS_APPLICATION_INFO.SET_MODULE(l_mod, l_act);
    EXCEPTION
        WHEN OTHERS THEN
            DBMS_APPLICATION_INFO.SET_MODULE(l_mod, l_act);
            RAISE;
    END collect;

    PROCEDURE set_enabled(p_name IN VARCHAR2, p_enabled IN VARCHAR2) IS
        t cap_target%ROWTYPE := get_target(p_name);
        l_mod   VARCHAR2(64);
        l_act   VARCHAR2(64);
    BEGIN
        DBMS_APPLICATION_INFO.READ_MODULE(l_mod, l_act);
        DBMS_APPLICATION_INFO.SET_MODULE('AWRCAP/cap_repo.set_enabled', NULL);
        IF UPPER(p_enabled) NOT IN ('Y', 'N') THEN
            RAISE_APPLICATION_ERROR(-20071, 'p_enabled must be Y or N');
        END IF;
        UPDATE cap_target SET enabled = UPPER(p_enabled) WHERE target_id = t.target_id;
        COMMIT;
        say('target ' || t.target_name || CASE UPPER(p_enabled) WHEN 'Y' THEN ' enabled' ELSE ' disabled' END);
        DBMS_APPLICATION_INFO.SET_MODULE(l_mod, l_act);
    EXCEPTION
        WHEN OTHERS THEN
            DBMS_APPLICATION_INFO.SET_MODULE(l_mod, l_act);
            RAISE;
    END set_enabled;

    PROCEDURE remove_target(p_name IN VARCHAR2) IS
        t      cap_target%ROWTYPE := get_target(p_name);
        v_rows NUMBER := 0;
        l_mod   VARCHAR2(64);
        l_act   VARCHAR2(64);
    BEGIN
        DBMS_APPLICATION_INFO.READ_MODULE(l_mod, l_act);
        DBMS_APPLICATION_INFO.SET_MODULE('AWRCAP/cap_repo.remove_target', NULL);
        -- Waits for a running collect chunk of these DBIDs to commit, so no
        -- chunk lands after the copies are deleted.
        FOR d IN (SELECT dbid FROM cap_target_dbid WHERE target_id = t.target_id
                  FOR UPDATE) LOOP
            FOR s IN (SELECT copy_table FROM cap_repo_source ORDER BY seq) LOOP
                EXECUTE IMMEDIATE 'DELETE FROM ' || s.copy_table || ' WHERE dbid = :1'
                    USING d.dbid;
                v_rows := v_rows + SQL%ROWCOUNT;
            END LOOP;
        END LOOP;
        DELETE FROM cap_target WHERE target_id = t.target_id;
        COMMIT;
        log_event(t.target_name, NULL, 'REMOVED', p_rows => v_rows);
        IF t.link_owned = 'Y' THEN
            close_link(t.db_link);
            BEGIN
                EXECUTE IMMEDIATE 'DROP DATABASE LINK ' || t.db_link;
            EXCEPTION
                WHEN OTHERS THEN
                    say('[WARN] could not drop link ' || t.db_link || ': ' || SQLERRM);
            END;
        END IF;
        say('target ' || t.target_name || ' removed, ' || v_rows || ' copied rows deleted');
        DBMS_APPLICATION_INFO.SET_MODULE(l_mod, l_act);
    EXCEPTION
        WHEN OTHERS THEN
            DBMS_APPLICATION_INFO.SET_MODULE(l_mod, l_act);
            RAISE;
    END remove_target;

    PROCEDURE set_link_password(p_name IN VARCHAR2, p_password IN VARCHAR2) IS
        t cap_target%ROWTYPE := get_target(p_name);
        l_mod   VARCHAR2(64);
        l_act   VARCHAR2(64);
    BEGIN
        DBMS_APPLICATION_INFO.READ_MODULE(l_mod, l_act);
        DBMS_APPLICATION_INFO.SET_MODULE('AWRCAP/cap_repo.set_link_password', NULL);
        IF t.link_owned = 'N' THEN
            RAISE_APPLICATION_ERROR(-20071, 'link ' || t.db_link || ' was made outside'
                                            || ' cap_repo: change it there');
        END IF;
        IF p_password IS NULL OR INSTR(p_password, '"') > 0 THEN
            RAISE_APPLICATION_ERROR(-20071, 'p_password must be given, without "');
        END IF;
        close_link(t.db_link);
        EXECUTE IMMEDIATE 'DROP DATABASE LINK ' || t.db_link;
        create_link(t.db_link, t.link_user, p_password, t.connect_string);
        probe(t.db_link);
        close_link(t.db_link);
        say('link ' || t.db_link || ' of target ' || t.target_name || ' recreated, probe OK');
        DBMS_APPLICATION_INFO.SET_MODULE(l_mod, l_act);
    EXCEPTION
        WHEN OTHERS THEN
            DBMS_APPLICATION_INFO.SET_MODULE(l_mod, l_act);
            RAISE;
    END set_link_password;

    -- No lock against collect: collect only inserts above each DBID's
    -- high-water mark and never reads the copies.
    PROCEDURE purge(p_days IN NUMBER DEFAULT NULL) IS
        v_days   NUMBER := p_days;
        v_status VARCHAR2(10);
        v_reason VARCHAR2(4000);
        v_cut    DATE;
        v_rows   NUMBER;
        v_total  NUMBER := 0;
        v_t0     PLS_INTEGER := DBMS_UTILITY.GET_TIME;
        -- Per DBID, the first snap_id to keep: the oldest snapshot that ended
        -- at or after the cut, or past the newest when none did. Fact rows
        -- below it go, also those of snapshots AWR purged unevenly.
        v_where  CONSTANT VARCHAR2(400) :=
            ' t WHERE t.snap_id < (SELECT c.cut_snap FROM (SELECT dbid,'
            || ' NVL(MIN(CASE WHEN end_interval_time >= :cut THEN snap_id END),'
            || ' MAX(snap_id) + 1) AS cut_snap FROM cap_h_snapshot GROUP BY dbid) c'
            || ' WHERE c.dbid = t.dbid)';
        l_mod   VARCHAR2(64);
        l_act   VARCHAR2(64);
    BEGIN
        DBMS_APPLICATION_INFO.READ_MODULE(l_mod, l_act);
        DBMS_APPLICATION_INFO.SET_MODULE('AWRCAP/cap_repo.purge', NULL);
        IF p_days IS NULL THEN
            SELECT MAX(value), MAX(status), MAX(reason)
            INTO   v_days, v_status, v_reason
            FROM   cap_cfg_check
            WHERE  knob = 'repo_retention_days';
            IF NVL(v_status, 'MISSING') <> 'OK' THEN
                RAISE_APPLICATION_ERROR(-20071, 'repo_retention_days is '
                    || NVL(v_status, 'MISSING') || ': ' || NVL(v_reason, 're-run ddl/05_config.sql')
                    || ' (or pass p_days)');
            END IF;
        ELSIF p_days < 0 OR p_days <> TRUNC(p_days) THEN
            RAISE_APPLICATION_ERROR(-20071, 'p_days must be 0 (keep everything) or a whole'
                                            || ' number of days, not ' || p_days);
        END IF;
        IF v_days = 0 THEN
            say('repo_retention_days 0: nothing purged');
            DBMS_APPLICATION_INFO.SET_MODULE(l_mod, l_act);
            RETURN;
        END IF;
        v_cut := SYSDATE - v_days;

        -- The snapshot copy goes last: every other DELETE reads it.
        FOR s IN (SELECT copy_table FROM cap_repo_source WHERE kind = 'F'
                  ORDER  BY CASE WHEN copy_table = 'CAP_H_SNAPSHOT' THEN 1 ELSE 0 END, seq) LOOP
            EXECUTE IMMEDIATE 'DELETE FROM ' || s.copy_table || v_where USING v_cut;
            v_rows  := SQL%ROWCOUNT;
            v_total := v_total + v_rows;
            say(RPAD(LOWER(s.copy_table), 26) || ' ' || v_rows || ' rows deleted');
        END LOOP;
        DELETE FROM cap_collect_log WHERE logged_at < v_cut;
        v_rows  := SQL%ROWCOUNT;
        v_total := v_total + v_rows;
        say(RPAD('cap_collect_log', 26) || ' ' || v_rows || ' rows deleted');
        COMMIT;
        log_event(NULL, NULL, 'PURGED', p_rows => v_total,
                  p_secs => ROUND((DBMS_UTILITY.GET_TIME - v_t0) / 100, 1),
                  p_msg  => 'snapshots that ended before ' || TO_CHAR(v_cut, 'YYYY-MM-DD HH24:MI')
                            || ' (' || CASE WHEN p_days IS NULL THEN 'repo_retention_days'
                                            ELSE 'p_days' END || ' ' || v_days || ')');
        DBMS_APPLICATION_INFO.SET_MODULE(l_mod, l_act);
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            log_event(NULL, NULL, 'ERROR', p_msg => 'purge: ' || SQLERRM);
            DBMS_APPLICATION_INFO.SET_MODULE(l_mod, l_act);
            RAISE;
    END purge;

    -- doctor.sql runs as SYSDBA under CURRENT_SCHEMA, and a private DB link
    -- resolves for the session user, so only this owner's definer's-rights
    -- code can use it.
    FUNCTION ping(p_name IN VARCHAR2) RETURN VARCHAR2 IS
        t     cap_target%ROWTYPE;
        v_err VARCHAR2(4000);
    BEGIN
        BEGIN
            t := get_target(p_name);
            probe(t.db_link);
        EXCEPTION
            WHEN OTHERS THEN v_err := SQLERRM;
        END;
        ROLLBACK;
        IF t.db_link IS NOT NULL THEN
            close_link(t.db_link);
        END IF;
        RETURN v_err;
    END ping;

    FUNCTION reader_expiry(p_name IN VARCHAR2) RETURN DATE IS
        t     cap_target%ROWTYPE;
        v_exp DATE;
    BEGIN
        BEGIN
            t := get_target(p_name);
            EXECUTE IMMEDIATE 'SELECT expiry_date FROM user_users@' || t.db_link INTO v_exp;
        EXCEPTION
            WHEN OTHERS THEN v_exp := NULL;
        END;
        ROLLBACK;
        IF t.db_link IS NOT NULL THEN
            close_link(t.db_link);
        END IF;
        RETURN v_exp;
    END reader_expiry;

