#!/usr/bin/env bash
# test/dbmint_copy_check.sh -- the M25.1 gate on dbmint: a repository's CAP_H_*
# copies hold exactly what its targets' DBA_HIST_* views hold.
#
#   test/dbmint_copy_check.sh <REPO_SCHEMA> [TARGET] [--collect] [--plant SOURCE]
#
#   REPO_SCHEMA     PDB1 schema of a repository install (CAPX2 etc.).
#   TARGET          one registered target (default: every enabled target).
#   --collect       cap_repo.collect first, so the dimensions are current.
#   --plant SOURCE  self-test: delete one copy row of the fact SOURCE (OSSTAT,
#                   ...) uncommitted, run the check in that session, roll back.
#                   Exit 0 only when exactly that row is reported.
#
# Runs test/repo_copy_check.sql (generated by repository/build.py) as SYSDBA in
# PDB1 under CURRENT_SCHEMA. Exit 0 equal, 1 differences or errors, 3 sync
# failed, 4 a lint failed, 5 a snapshot landed or a collect ran during the
# check (rerun). Log /tmp/dbmint_copy_check.<REPO_SCHEMA>.log.
set -u
HERE=$(cd "$(dirname "$0")/.." && pwd)
REPO=${1:?repository schema}; shift
TARGET=-; COLLECT=0; PLANT=-
while [ $# -gt 0 ]; do
  case "$1" in
    --collect) COLLECT=1;;
    --plant) PLANT=${2:?--plant needs a source}; shift;;
    --*) echo "unknown arg $1" >&2; exit 2;;
    *) TARGET=$1;;
  esac; shift
done
REMOTE=awr_cap_copycheck
LOG=/tmp/dbmint_copy_check.$REPO.log

python3 "$HERE"/repository/build.py --check || exit 4
"$HERE"/test/lint_dba_hist.sh >/dev/null || exit 4

rsync -az --delete -e 'ssh -p 2200' \
  --exclude .git --exclude .claude --exclude reports --exclude '__pycache__' \
  --exclude grafana/.ords.env --exclude grafana/ords/config --exclude grafana/.env \
  "$HERE"/ oracle@dbmint:~/"$REMOTE"/ || exit 3

{
  echo "WHENEVER SQLERROR EXIT FAILURE ROLLBACK"
  echo "ALTER SESSION SET CONTAINER = PDB1;"
  echo "ALTER SESSION SET CURRENT_SCHEMA = $REPO;"
  if [ $COLLECT = 1 ]; then
    echo "SET SERVEROUTPUT ON SIZE UNLIMITED FORMAT WRAPPED"
    [ "$TARGET" = - ] && echo "EXEC cap_repo.collect" || echo "EXEC cap_repo.collect('$TARGET')"
  fi
  echo "@test/repo_copy_check.sql $TARGET $PLANT"
  echo "EXIT"
} | ssh -p 2200 oracle@dbmint "export ORACLE_SID=cdb1 ORAENV_ASK=NO; . oraenv >/dev/null 2>&1; cd ~/$REMOTE && sqlplus -S -L / as sysdba" > "$LOG" 2>&1

grep -E '^COPYCHECK' "$LOG"
RESULT=$(sed -n 's/^COPYCHECK-RESULT \([A-Z]*\).*/\1/p' "$LOG")
if [ "$PLANT" != - ]; then
  DIFF=$(grep -E '^COPYCHECK .* (DIFF|ERROR)' "$LOG")
  if [ "$RESULT" = DIFFERENT ] && grep -q "^COPYCHECK-PLANTED .* rows=1$" "$LOG" \
     && [ "$(echo "$DIFF" | wc -l)" = 1 ] \
     && echo "$DIFF" | grep -qiE " $PLANT +F .* src_only=1 copy_only=0 DIFF$"; then
    echo "### planted row caught: one row of $PLANT, nothing else"; exit 0
  fi
  echo "### planted row NOT caught as exactly one difference (log $LOG)"; exit 1
fi
case "$RESULT" in
  EQUAL) echo "### copies equal their sources"; exit 0;;
  MOVED) echo "### INCONCLUSIVE: a snapshot landed or a collect ran during the check; rerun"; exit 5;;
  *) echo "### copies DIFFER or the check failed (log $LOG)"
     grep -E 'ORA-|PLS-|SP2-' "$LOG" | head -10; exit 1;;
esac
