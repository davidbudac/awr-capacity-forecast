#!/usr/bin/env bash
# test/standalone_test.sh -- test the standalone queries on the dbmint VM
# against designed series (SYSDBA + CURRENT_SCHEMA, PDB1).
#
#   test/standalone_test.sh <SCHEMA> [--no-fixture]
#
#   <SCHEMA>      throwaway schema in PDB1 (CREATE TABLE / VIEW + USERS quota).
#                 Never an Oracle-maintained one: the fixture creates objects
#                 named like the AWR views there, and refuses to otherwise.
#   --no-fixture  skip test/standalone_fixture.sql (views + test only)
#
# What it does:
#   1. Offline: the CTE chain db .. res of standalone/tbspc_capacity.sql and
#      standalone/tbspc_monitor.sql must be the same text, the monitor's
#      live_pct lines aside (exit 4 with the diff otherwise).
#   2. Offline: cuts the SELECT out of both files (from "WITH prm AS (" to
#      the first line that ends in a semicolon), unchanged or with one prm
#      knob edited, and writes each behind CREATE OR REPLACE VIEW into
#      views.sql. The shipped text is what the test runs.
#   3. rsync to ~/awr_cap_<schema>/ (views.sql into test/standalone_gen/),
#      then in <SCHEMA>: test/standalone_fixture.sql, the views,
#      test/standalone_test.sql, and both files run as they are (@file)
#      against the fixture.
# Exit status: the SQL*Plus exit status of the failing step, or 1 when the
# log holds an ORA- / SP2- / PLS- line or the unchanged files listed no
# row. Log: /tmp/standalone_test_<SCHEMA>.log, its RESULT / FAIL lines are
# echoed at the end.
set -u
HERE=$(cd "$(dirname "$0")/.." && pwd)
SCHEMA=${1:?schema}; shift
FIXTURE=1
while [ $# -gt 0 ]; do
  case "$1" in
    --no-fixture) FIXTURE=0;;
    *) echo "unknown arg $1" >&2; exit 2;;
  esac; shift
done
REMOTE=awr_cap_$(echo "$SCHEMA" | tr 'A-Z' 'a-z')
SSH="ssh -p 2200 oracle@dbmint"
LOG=/tmp/standalone_test_${SCHEMA}.log
CAP=standalone/tbspc_capacity.sql
MON=standalone/tbspc_monitor.sql

# ---- 1. the shared forecast is the same text in both files ----
# chain <file>: from "db AS (" to the end of the res CTE.
chain() {
  awk '/^     db AS \($/ { on = 1 }
       on { print }
       on && /^     res AS \($/ { res = 1 }
       res && /^     \),?$/ { exit }' "$HERE/$1"
}
# The monitor adds live_pct in the live and lim CTEs (two lines, a comma
# and the comment that shows the empty body). Take those out and compare.
if ! diff <(chain $CAP) \
          <(chain $MON | sed -e '/ AS live_pct,\{0,1\}$/d' \
                             -e 's/, 0 AS live_pct FROM dual/ FROM dual/' \
                             -e 's/ AS cap_b,$/ AS cap_b/'); then
  echo "standalone_test: the db .. res chain of $CAP and $MON differs (above): not syncing"
  exit 4
fi
[ "$(chain $CAP | wc -l)" -gt 300 ] || { echo "standalone_test: db .. res chain not found in $CAP"; exit 4; }
echo "standalone_test: db .. res identical in both files ($(chain $CAP | wc -l) lines, live_pct aside)"

# ---- 2. the files' SELECTs as views ----
GEN=$(mktemp -d) || exit 2
trap 'rm -rf "$GEN"' EXIT
# gen_view <file> <view> [sed expression that edits one prm line]
gen_view() {
  local q q2
  q=$(awk '/^WITH prm AS \($/ { on = 1 }
           on { print }
           on && /;[[:space:]]*$/ { exit }' "$HERE/$1")
  case "$q" in
    "WITH prm AS ("*";") ;;
    *) echo "standalone_test: no SELECT found in $1" >&2; exit 4;;
  esac
  if [ $# -ge 3 ]; then
    q2=$(printf '%s\n' "$q" | sed -e "$3")
    [ "$(diff <(printf '%s\n' "$q") <(printf '%s\n' "$q2") | grep -c '^>')" = 1 ] \
      || { echo "standalone_test: knob edit \"$3\" did not change exactly one line of $1" >&2; exit 4; }
    q=$q2
  fi
  printf 'CREATE OR REPLACE VIEW %s AS\n%s\n\n' "$2" "$q"
}
{
  cat <<'SQL'
-- Generated by test/standalone_test.sh from standalone/*.sql. Not kept.
SET DEFINE OFF
SET SQLBLANKLINES ON
SET FEEDBACK OFF
WHENEVER SQLERROR EXIT FAILURE
DECLARE
    v_maint VARCHAR2(1);
BEGIN
    SELECT MAX(oracle_maintained) INTO v_maint FROM all_users
    WHERE  username = SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA');
    IF v_maint IS NULL OR v_maint <> 'N' THEN
        RAISE_APPLICATION_ERROR(-20001, 'standalone_gen: CURRENT_SCHEMA is not a test schema.');
    END IF;
END;
/
SQL
  gen_view $CAP sa_cap_v
  gen_view $CAP sa_cap_q0_v   's/14        AS quiet_days,/0         AS quiet_days,/'
  gen_view $CAP sa_cap_disk_v 's/CAST(NULL AS NUMBER) AS disk_free_gb,/30.375 AS disk_free_gb,/'
  gen_view $MON sa_mon_v
  gen_view $MON sa_mon_all_v  's/1         AS alerts_only /0         AS alerts_only /'
} > "$GEN/views.sql" || exit 4
[ "$(grep -c '^CREATE OR REPLACE VIEW ' "$GEN/views.sql")" = 5 ] || { echo "standalone_test: views.sql incomplete"; exit 4; }

# ---- 3. sync and run ----
rsync -az --delete -e 'ssh -p 2200' \
  --exclude .git --exclude .claude --exclude reports --exclude '__pycache__' \
  --exclude grafana/.ords.env --exclude grafana/ords/config --exclude grafana/.env \
  "$HERE"/ oracle@dbmint:~/"$REMOTE"/ || exit 3
rsync -az -e 'ssh -p 2200' "$GEN"/ oracle@dbmint:~/"$REMOTE"/test/standalone_gen/ || exit 3

PRE="ALTER SESSION SET CONTAINER = PDB1;
ALTER SESSION SET CURRENT_SCHEMA = $SCHEMA;"
SMOKE="### the files as they are, world W3"
STEPS=()
[ $FIXTURE = 1 ] && STEPS+=("@test/standalone_fixture.sql")
STEPS+=("@test/standalone_gen/views.sql")
STEPS+=("@test/standalone_test.sql")
STEPS+=("PROMPT $SMOKE
UPDATE sa_ctx SET world = 'W3', asof_i = 200;
COMMIT;
@$CAP
@$MON
UPDATE sa_ctx SET world = 'W1', asof_i = 200;
COMMIT;")

: > "$LOG"; rc=0
for step in "${STEPS[@]}"; do
  echo "### $step" | head -1 | tee -a "$LOG"
  t0=$(date +%s)
  $SSH 'bash -s' <<REMOTE_EOF >> "$LOG" 2>&1
export ORACLE_SID=cdb1; export ORAENV_ASK=NO; . oraenv >/dev/null 2>&1
cd ~/$REMOTE && sqlplus -S -L / as sysdba <<'SQL'
WHENEVER SQLERROR EXIT FAILURE
$PRE
$step
EXIT
SQL
REMOTE_EOF
  src=$?
  echo "### elapsed $(( $(date +%s) - t0 )) s" | tee -a "$LOG"
  [ $src -ne 0 ] && { echo "### step failed (exit $src)" | tee -a "$LOG"; rc=$src; break; }
done
grep -E "RESULT:|FAIL|ORA-|PLS-|SP2-|Warning: .* compilation errors|step failed" "$LOG" | grep -v "^  PASS" | head -60
if [ $rc = 0 ]; then
  if grep -qE "ORA-|PLS-|SP2-" "$LOG"; then
    echo "standalone_test: error lines in the log"; rc=1
  elif [ "$(sed -n "/^$SMOKE/,\$p" "$LOG" | grep -c 'M_SOON')" != 2 ]; then
    echo "standalone_test: the unchanged files did not both list M_SOON"; rc=1
  fi
fi
echo "log: $LOG  (exit $rc)"
exit $rc
